/**
 * Thumb-drag geometry capture on a mixed-size document (issue
 * tuxbooks-x27.4, evidence for the thumb fix tuxbooks-x27.5).
 *
 * This suite CAPTURES and REPORTS; it never asserts thumb behavior —
 * per the parent spec, the thumb fix has no regression test by decision,
 * and this capture is the evidence instrument instead. It drives a real
 * native scrollbar thumb drag through trusted input (Playwright mouse,
 * the browser's input pipeline) over the committed mixed-size fixture,
 * and records:
 *
 * - scroll-height changes while the drag is in flight (the T1 mechanism:
 *   page-measurement corrections rewriting slot heights mid-drag);
 * - thumb-versus-cursor error over the traveled distance, measured
 *   against the grab-time (frozen) geometry;
 * - re-anchor firings, detected as programmatic scrollTop writes on the
 *   scroll container during the drag (the T2 mechanism,
 *   reanchorByFraction; a native thumb drag updates the scroll offset
 *   inside the browser input path and never calls the JS setter, so
 *   every intercepted write is app-driven).
 *
 * Run it explicitly: `just test-e2e-capture` (opt-in, Xvfb, never CI).
 * The report lands in artifacts/e2e/<runId>/thumb-drag-capture.json and
 * the procedure lives in docs/research/pdf-viewer-perf-findings.md
 * (Symptom 2). The fixture is generated by
 * scripts/make-thumb-capture-fixture.py and committed; its provenance is
 * recorded with the capture verdict.
 *
 * Fixture design (why the mechanism fires here): the reader estimates
 * every unmeasured page from a three-page opening sample (pages 1, 2,
 * last; median by area). The fixture's front matter (pages 1-8,
 * 500x650pt) wins that sample, so all 384 body pages (612x792/900/720)
 * are reserved too short and correct upward as the drag's render window
 * measures them. Page 200 (700x1100) is wider than every sampled page,
 * so measuring it grows the fit-width reference — the path that can
 * reach reanchorByFraction.
 */

/** Fixed window geometry: the capture defines its own reference conditions. */
const WINDOW_WIDTH = 1600;
const WINDOW_HEIGHT = 1000;

/** Drag shape, matched to the 2026-10-23 uniform-GeoTopo capture: 60 steps of 10 cursor px. */
const DRAG_STEPS = 60;
const DRAG_STEP_PX = 10;

/**
 * Calibration probe offsets (CSS px) around the arrow-buttons thumb-center
 * model, tried in order. The 2026-10-23 capture grabbed at -9 px.
 */
const PROBE_OFFSETS = [0, -4, -8, -12, 4, 8, 12, -16, 16];

/**
 * A probe press counts as a thumb grab when the follow-up nudge moved the
 * document a drag-scaled amount. A track press jumps by pages (tens of
 * thousands of px); a thumb grab at ~350 scroll px per cursor px moves a
 * few thousand.
 */
const GRAB_MAX_JUMP_PX = 20_000;
/** Below this the press did not take hold at all (wrong x, dead zone). */
const GRAB_MIN_MOVE_PX = 50;

/** Interpretation thresholds for the verdict, stated so the report is self-contained. */
const VERDICT = {
  /** Materiality: the uniform baseline ended 64 px off over ~190,000 px traveled (0.03%). */
  uniformBaselineErrorPx: 64,
  /** A visible jump: ~3 px of thumb travel on a ~900 px track, far above baseline noise. */
  jumpErrorPx: 1_000,
} as const;

/** Average body-page height in points; converts position error into pages. */
const MEAN_BODY_PAGE_PT = 804;

type Geometry = {
  scrollTop: number;
  scrollHeight: number;
  clientHeight: number;
  clientWidth: number;
  offsetWidth: number;
  rectTop: number;
  rectLeft: number;
};

type Sample = { t: number; scrollTop: number; scrollHeight: number };

type AppWrite = { t: number; from: number; to: number };

type DragStep = { step: number; cursorY: number; tStart: number; tEnd: number };

type Collected = { samples: Sample[]; appWrites: AppWrite[]; t0: number };

type CaptureGlobals = typeof globalThis & {
  __tuxbooksThumbCapture?: {
    stopAndCollect: () => Collected;
  };
};

function sha256OfFixture(fixturePath: string): string {
  return createHash("sha256").update(readFileSync(fixturePath)).digest("hex");
}

/** Geometry of the PDF scroll container. */
async function readContainer(page: Page): Promise<Geometry> {
  return page.evaluate(() => {
    const container = document.querySelector<HTMLElement>("[data-testid=reader-content]");
    if (!container) throw new Error("PDF scroll container not found");
    const rect = container.getBoundingClientRect();
    return {
      scrollTop: container.scrollTop,
      scrollHeight: container.scrollHeight,
      clientHeight: container.clientHeight,
      clientWidth: container.clientWidth,
      offsetWidth: container.offsetWidth,
      rectTop: rect.top,
      rectLeft: rect.left,
    };
  });
}

/** Apply a window size through the renderer and wait until it sticks. */
async function fixWindowSize(page: Page): Promise<void> {
  await page.evaluate(([w, h]) => window.resizeTo(w!, h!), [WINDOW_WIDTH, WINDOW_HEIGHT]);
  await expect
    .poll(async () => {
      await page.evaluate(([w, h]) => window.resizeTo(w!, h!), [WINDOW_WIDTH, WINDOW_HEIGHT]);
      await page.waitForTimeout(200);
      return page.evaluate(() => ({ width: window.innerWidth }));
    })
    // outerHeight includes the WM title bar; inner width is exact.
    .toEqual({ width: WINDOW_WIDTH });
}

/**
 * Install the in-page instruments on the PDF scroll container: an 8 ms
 * sampler (one sample per animation frame, bench-sampler pattern) and a
 * scrollTop setter patch that records programmatic writes. All clock
 * reads use the page's performance.now(), so page-side step timestamps
 * and sample timestamps share one clock; stopAndCollect() reports the
 * install time so the Node side can rebase.
 */
async function installInstruments(page: Page): Promise<void> {
  await page.evaluate(() => {
    const container = document.querySelector<HTMLElement>("[data-testid=reader-content]");
    if (!container) throw new Error("PDF scroll container not found");
    const globals = globalThis as CaptureGlobals;
    if (globals.__tuxbooksThumbCapture) return;

    const protoDesc = Object.getOwnPropertyDescriptor(Element.prototype, "scrollTop");
    if (!protoDesc) throw new Error("scrollTop accessor not found");

    const state = {
      t0: performance.now(),
      running: true,
      samples: [] as Sample[],
      appWrites: [] as AppWrite[],
    };

    const sampler = window.setInterval(() => {
      if (!state.running) return;
      requestAnimationFrame(() => {
        if (!state.running) return;
        state.samples.push({
          t: performance.now() - state.t0,
          scrollTop: container.scrollTop,
          scrollHeight: container.scrollHeight,
        });
      });
    }, 8);

    Object.defineProperty(container, "scrollTop", {
      configurable: true,
      get() {
        return protoDesc.get!.call(container);
      },
      set(value: number) {
        const from = protoDesc.get!.call(container);
        if (value !== from) {
          state.appWrites.push({
            t: performance.now() - state.t0,
            from,
            to: value,
          });
        }
        protoDesc.set!.call(container, value);
      },
    });

    globals.__tuxbooksThumbCapture = {
      stopAndCollect() {
        state.running = false;
        window.clearInterval(sampler);
        return {
          samples: state.samples.slice(),
          appWrites: state.appWrites.slice(),
          t0: state.t0,
        };
      },
    };
  });
}

type ThumbModel = {
  trackX: number;
  trackTop: number;
  trackLen: number;
  arrowLen: number;
  usable: number;
  thumbLen: number;
  pxPerCursor: number;
};

/**
 * The thumb model for Chromium's classic scrollbar on Linux: square arrow
 * buttons at both track ends, thumb length proportional to the visible
 * fraction of the usable track. pxPerCursor is the drag ratio: how many
 * scroll px one cursor px moves at this geometry.
 */
function thumbModel(geometry: Geometry): ThumbModel {
  const scrollbarWidth = geometry.offsetWidth - geometry.clientWidth;
  if (scrollbarWidth <= 0) throw new Error("no classic scrollbar on the container");
  const trackLen = geometry.clientHeight;
  const arrowLen = scrollbarWidth;
  const usable = trackLen - 2 * arrowLen;
  const maxScroll = geometry.scrollHeight - geometry.clientHeight;
  const thumbLen = Math.max(
    scrollbarWidth,
    (geometry.clientHeight / geometry.scrollHeight) * usable,
  );
  return {
    trackX: geometry.rectLeft + geometry.clientWidth + scrollbarWidth / 2,
    trackTop: geometry.rectTop,
    trackLen,
    arrowLen,
    usable,
    thumbLen,
    pxPerCursor: maxScroll / (usable - thumbLen),
  };
}

/** Predicted thumb center y for a scrollTop, under the given model. */
function predictedThumbCenterY(model: ThumbModel, geometry: Geometry, scrollTop: number): number {
  const maxScroll = geometry.scrollHeight - geometry.clientHeight;
  const fraction = Math.min(1, Math.max(0, scrollTop / maxScroll));
  return (
    model.trackTop +
    model.arrowLen +
    fraction * (model.usable - model.thumbLen) +
    model.thumbLen / 2
  );
}

type Calibration = {
  grabCursorY: number;
  grabScrollTop: number;
  probeOffset: number;
  probes: { offset: number; moved: number }[];
};

/**
 * Find and grab the thumb: press at the modeled center shifted by each
 * probe offset, nudge 3 px down, and keep the first press that moved the
 * document a drag-scaled amount. Mis-presses are released and the start
 * position restored (pre-instrumentation, so measurement pollution from
 * probes never lands in the drag window). Returns with the button held
 * down, ready for the drag.
 */
async function calibrateAndGrab(page: Page, startScrollTop: number): Promise<Calibration> {
  const geometry = await readContainer(page);
  const model = thumbModel(geometry);
  const modelCenterY = predictedThumbCenterY(model, geometry, startScrollTop);
  const probes: { offset: number; moved: number }[] = [];

  for (const offset of PROBE_OFFSETS) {
    const cursorY = modelCenterY + offset;
    const before = (await readContainer(page)).scrollTop;
    await page.mouse.move(model.trackX, cursorY);
    await page.mouse.down();
    await page.mouse.move(model.trackX, cursorY + 3);
    await page.waitForTimeout(60);
    const after = (await readContainer(page)).scrollTop;
    const moved = Math.abs(after - before);

    if (moved >= GRAB_MIN_MOVE_PX && moved <= GRAB_MAX_JUMP_PX) {
      probes.push({ offset, moved });
      // Keep holding: the drag continues from exactly this press.
      return {
        grabCursorY: cursorY + 3,
        grabScrollTop: after,
        probeOffset: offset,
        probes,
      };
    }

    await page.mouse.up();
    probes.push({ offset, moved });
    if (moved > GRAB_MAX_JUMP_PX) {
      // Track press: the document jumped to the press point. Restore.
      await page.evaluate((top) => {
        const container = document.querySelector<HTMLElement>("[data-testid=reader-content]");
        if (container) container.scrollTop = top;
      }, startScrollTop);
      await page.waitForTimeout(250);
    }
  }
  throw new Error(`thumb calibration failed: no probe grabbed (probes=${JSON.stringify(probes)})`);
}

test.describe("thumb-drag capture (mixed-size document)", () => {
  test("capture thumb-drag geometry", async ({ page }) => {
    test.setTimeout(180_000);

    await fixWindowSize(page);
    await openInReader(page, "Thumb Capture Mixed (PDF)");
    await waitForRendered(page, 1);

    // Start from a fixed offset (~8% into the document): past the opening
    // render window, so the drag travels into unmeasured pages.
    const startScrollTop = await page.evaluate(() => {
      const container = document.querySelector<HTMLElement>("[data-testid=reader-content]");
      if (!container) throw new Error("PDF scroll container not found");
      const target = Math.round(container.scrollHeight * 0.08);
      container.scrollTop = target;
      return container.scrollTop;
    });
    await page.waitForTimeout(600);

    const calibration = await calibrateAndGrab(page, startScrollTop);
    await installInstruments(page);
    const startGeometry = await readContainer(page);
    const grabModel = thumbModel(startGeometry);

    // The drag: 60 steps x 10 cursor px downward, one trusted mousemove
    // per step while the calibration press is still held. Each step's
    // wall time is recorded so samples map to steps (one shared clock).
    const dragSteps: DragStep[] = [];
    const dragStartedAt = await page.evaluate(() => performance.now());
    let cursorY = calibration.grabCursorY;
    for (let step = 0; step < DRAG_STEPS; step += 1) {
      const tStart = await page.evaluate(() => performance.now());
      cursorY += DRAG_STEP_PX;
      await page.mouse.move(grabModel.trackX, cursorY);
      const tEnd = await page.evaluate(() => performance.now());
      dragSteps.push({ step, cursorY, tStart, tEnd });
    }
    // Let the last frames land, then release and settle.
    await page.waitForTimeout(400);
    await page.mouse.up();
    await page.waitForTimeout(400);

    const collected: Collected = await page.evaluate(() => {
      const handle = (globalThis as CaptureGlobals).__tuxbooksThumbCapture;
      if (!handle) throw new Error("capture instruments were never installed");
      return handle.stopAndCollect();
    });
    const endGeometry = await readContainer(page);
    const endModel = thumbModel(endGeometry);
    const endCursorY = cursorY;

    // -- Analysis -----------------------------------------------------------

    // Sample timestamps are relative to the in-page install time; the
    // step timestamps are raw performance.now(). Rebase via the offset.
    const toSampleT = (pageT: number) => pageT - collected.t0;
    const dragStartSampleT = toSampleT(dragStartedAt);
    const dragEndSampleT = toSampleT(dragSteps[dragSteps.length - 1].tEnd) + 50;

    // Scroll-height events: consecutive samples whose scrollHeight differs.
    const heightEvents = [] as {
      t: number;
      from: number;
      to: number;
      delta: number;
      duringDrag: boolean;
    }[];
    for (let i = 1; i < collected.samples.length; i += 1) {
      const prev = collected.samples[i - 1];
      const curr = collected.samples[i];
      if (curr.scrollHeight !== prev.scrollHeight) {
        heightEvents.push({
          t: curr.t,
          from: prev.scrollHeight,
          to: curr.scrollHeight,
          delta: curr.scrollHeight - prev.scrollHeight,
          duringDrag: curr.t >= dragStartSampleT && curr.t <= dragEndSampleT,
        });
      }
    }
    const heightEventsDuringDrag = heightEvents.filter((event) => event.duringDrag);

    // Re-anchor firings: programmatic scrollTop writes inside the drag window.
    const appWritesDuringDrag = collected.appWrites.filter(
      (write) => write.t >= dragStartSampleT && write.t <= dragEndSampleT,
    );

    // Thumb-versus-cursor error against the grab-time (frozen) geometry:
    // predicted scrollTop maps cursor travel by the grab-time ratio. The
    // grab point carries the calibration nudge, so cursor travel counts
    // from where the held drag actually started.
    const predictedEndScrollTop =
      calibration.grabScrollTop + (endCursorY - calibration.grabCursorY) * grabModel.pxPerCursor;
    const actualEndScrollTop = endGeometry.scrollTop;
    const traveledPx = actualEndScrollTop - calibration.grabScrollTop;
    const finalErrorPx = actualEndScrollTop - predictedEndScrollTop;

    // Per-step error from samples: the last sample at or before each
    // step's end, against the same frozen-geometry prediction.
    const perStep = dragSteps
      .map((step) => {
        const tSample = toSampleT(step.tEnd);
        let sample: Sample | null = null;
        for (const candidate of collected.samples) {
          if (candidate.t <= tSample) sample = candidate;
          else break;
        }
        if (!sample) return null;
        const predicted =
          calibration.grabScrollTop +
          (step.cursorY - calibration.grabCursorY) * grabModel.pxPerCursor;
        return {
          step: step.step,
          t: sample.t,
          scrollTop: sample.scrollTop,
          predicted,
          error: sample.scrollTop - predicted,
        };
      })
      .filter((entry) => entry !== null);
    const maxAbsErrorPx = Math.max(...perStep.map((entry) => Math.abs(entry.error)));

    // Thumb-under-cursor at the end, under live geometry: where the cursor
    // sits within the usable track versus where the thumb actually is.
    // Prediction-free: this is the user-visible jump, not a model artifact.
    const endMaxScroll = endGeometry.scrollHeight - endGeometry.clientHeight;
    const cursorTrackFrac = (endCursorY - endModel.trackTop - endModel.arrowLen) / endModel.usable;
    const thumbTrackFrac = actualEndScrollTop / endMaxScroll;
    const thumbCursorGapTrackPx = Math.abs(cursorTrackFrac - thumbTrackFrac) * endModel.usable;
    const endThumbCenterY = predictedThumbCenterY(endModel, endGeometry, actualEndScrollTop);
    const thumbUnderCursorAtEnd = Math.abs(endCursorY - endThumbCenterY) <= endModel.thumbLen / 2;

    // -- Verdict ------------------------------------------------------------

    const t1HeightEvents = heightEventsDuringDrag.length;
    const heightDeltaPx = heightEventsDuringDrag.reduce((sum, event) => sum + event.delta, 0);
    const errorMultipleOfBaseline = maxAbsErrorPx / VERDICT.uniformBaselineErrorPx;
    // The confirmed flag keys off the settled END error, not the per-step
    // max: per-step samples can land before a move's scroll paints and run
    // short by up to one predicted step (~7k px), which aliasing also
    // inflates. The end state is settled and aliasing-proof.
    const t1Confirmed = t1HeightEvents > 0 && Math.abs(finalErrorPx) >= VERDICT.jumpErrorPx;
    const t2Firings = appWritesDuringDrag.length;

    // Per-step actual deltas: quantization to step multiples is the capture
    // racing the frame clock (aliasing redistributes deltas across steps),
    // but the total is preserved — lost travel is predicted minus actual.
    const stepDeltas: number[] = [];
    for (let i = 1; i < perStep.length; i += 1) {
      stepDeltas.push(perStep[i].scrollTop - perStep[i - 1].scrollTop);
    }
    const deadSteps = stepDeltas.filter((delta) => Math.abs(delta) < 1).length;
    const lostTravelPx = predictedEndScrollTop - calibration.grabScrollTop - traveledPx;

    const verdict = {
      t1: {
        heightEventsDuringDrag: t1HeightEvents,
        heightDeltaPx,
        maxAbsErrorPx,
        errorMultipleOfBaseline,
        confirmed: t1Confirmed,
        mechanism: "scroll-height corrections land mid-drag (T1)",
      },
      t2: {
        reanchorFirings: t2Firings,
        writes: appWritesDuringDrag,
        fired: t2Firings > 0,
        mechanism: "fit-scale change reaches reanchorByFraction mid-drag (T2)",
      },
      leading: t1Confirmed
        ? "T1: layout height corrections landing mid-drag"
        : t2Firings > 0
          ? "T2: re-anchor-by-fraction firing mid-drag"
          : "not reproduced",
    };

    // -- Harness sanity only (never thumb behavior) --------------------------
    expect(traveledPx).toBeGreaterThan(50_000);
    expect(collected.samples.length).toBeGreaterThan(60);
    expect(endGeometry.scrollHeight).toBeGreaterThan(startGeometry.scrollHeight);

    const report = {
      issue: "tuxbooks-x27.4",
      fixture: {
        path: "tests/fixtures/books/thumb-capture-mixed.pdf",
        sha256: sha256OfFixture(
          path.join(repoRoot, "tests", "fixtures", "books", "thumb-capture-mixed.pdf"),
        ),
        design:
          "392 pages: 8x front matter 500x650 (opening-sample anchor), body cycling " +
          "612x792/900/720, page 200 oversized 700x1100 (fit-width reference shift)",
      },
      window: { width: WINDOW_WIDTH, height: WINDOW_HEIGHT },
      calibration: {
        probeOffsetPx: calibration.probeOffset,
        grabScrollTop: calibration.grabScrollTop,
        pxPerCursor: grabModel.pxPerCursor,
        probes: calibration.probes,
      },
      drag: {
        steps: DRAG_STEPS,
        stepPx: DRAG_STEP_PX,
        cursorPx: DRAG_STEPS * DRAG_STEP_PX,
        predictedScrollPx: predictedEndScrollTop - calibration.grabScrollTop,
        actualScrollPx: traveledPx,
      },
      geometry: { start: startGeometry, end: endGeometry },
      metrics: {
        finalErrorPx,
        finalErrorPctOfTravel: (finalErrorPx / traveledPx) * 100,
        maxAbsErrorPx,
        finalErrorPages: finalErrorPx / MEAN_BODY_PAGE_PT,
        // Live-geometry, prediction-free jump evidence.
        cursorTrackFrac,
        thumbTrackFrac,
        thumbCursorGapTrackPx,
        thumbUnderCursorAtEnd,
        // Travel accounting: aliasing redistributes per-step deltas but
        // preserves totals, so predicted-minus-actual is real lost travel.
        lostTravelPx,
        deadSteps,
        scrollHeightChangePx: endGeometry.scrollHeight - startGeometry.scrollHeight,
        heightEventsTotal: heightEvents.length,
        heightEventsDuringDrag: t1HeightEvents,
        heightDeltaPxDuringDrag: heightDeltaPx,
        reanchorWritesDuringDrag: t2Firings,
      },
      verdict,
      heightEventsDuringDrag,
      appWritesDuringDrag,
      allAppWrites: collected.appWrites,
      perStepErrors: perStep,
    };

    const outPath = path.join(artifactsDir, "thumb-drag-capture.json");
    writeFileSync(outPath, `${JSON.stringify(report, null, 2)}\n`);

    console.log(
      `[capture] thumb-drag: heightEvents=${t1HeightEvents} ` +
        `reanchorWrites=${t2Firings} finalErrorPx=${finalErrorPx.toFixed(0)} ` +
        `(${((finalErrorPx / traveledPx) * 100).toFixed(3)}% of ${traveledPx.toFixed(0)} px) ` +
        `maxAbsErrorPx=${maxAbsErrorPx.toFixed(0)} lostTravelPx=${lostTravelPx.toFixed(0)} ` +
        `gapTrackPx=${thumbCursorGapTrackPx.toFixed(0)} ` +
        `thumbUnderCursorAtEnd=${thumbUnderCursorAtEnd} -> ${verdict.leading}`,
    );
    console.log(`[capture] report written to ${outPath}`);
  });
});
